import { expect, test } from '@playwright/test';

test('Navigation Page List selects as a block, reorders, converts and supports Undo', async ({ page }) => {
  await page.goto('/studio/ui/blocks/navigation');
  await expect(page.locator('.ui-block-specimen')).toHaveAttribute('data-ready', 'true');
  const editor = page.locator('.ui-library-canvas');
  const pageListBlock = editor.getByRole('group', { name: 'Page List block', exact: true });
  await expect(pageListBlock).toBeVisible();
  await expect(editor.locator('[data-navigation-page-list] li')).toHaveCount(3);
  const rootItems = editor.locator('ul.template-navigation-items').first().locator(':scope > li');
  await expect(rootItems.nth(3)).toHaveAttribute('data-navigation-page-list');
  await expect(editor.getByRole('button', { name: 'Add Page List', exact: true })).toHaveCount(0);
  await pageListBlock.click();
  await expect(pageListBlock).toHaveClass(/is-selected/);
  await expect(pageListBlock.getByRole('group', { name: 'Page List block tools', exact: true })).toBeVisible();
  await editor.getByRole('button', { name: 'Move Page List left', exact: true }).click();
  await expect(rootItems.nth(2)).toHaveAttribute('data-navigation-page-list');
  await expect(rootItems.nth(3)).toContainText('Guides');
  await expect(editor.getByRole('complementary', { name: 'Page List settings', exact: true })).toContainText('Automatically displays published pages in the menu.');
  await pageListBlock.getByRole('button', { name: 'Select parent block: Navigation', exact: true }).click();
  await expect(editor.getByRole('button', { name: 'Remove Page List', exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: 'Undo specimen change' }).click();
  await expect(rootItems.nth(3)).toHaveAttribute('data-navigation-page-list');
  await page.getByRole('group', { name: 'Specimen view' }).getByRole('button', { name: 'Preview', exact: true }).click();
  await expect(page.locator('.ui-block-canvas [data-navigation-page-list]')).toBeVisible();
  await expect(page.locator('.ui-block-canvas [data-navigation-page-list] a')).toHaveCount(3);
  await page.getByRole('group', { name: 'Specimen view' }).getByRole('button', { name: 'Edit', exact: true }).click();
  await pageListBlock.click();
  await pageListBlock.getByRole('button', { name: 'Edit Page List', exact: true }).click();
  await expect(editor.locator('[data-navigation-page-list]')).toHaveCount(0);
  await expect(editor.getByRole('textbox', { name: 'Navigation link text: Home', exact: true })).toHaveCount(2);
  await expect(editor.getByRole('textbox', { name: 'Navigation link text: About', exact: true })).toHaveCount(2);
  await expect(editor.getByRole('textbox', { name: 'Navigation link text: Guides', exact: true })).toHaveCount(2);
  await page.getByRole('button', { name: 'Undo specimen change' }).click();
  await expect(editor.locator('[data-navigation-page-list]')).toBeVisible();
  await expect(editor.getByRole('textbox', { name: 'Navigation link text: Home', exact: true })).toHaveCount(1);
  await expect(editor.getByRole('textbox', { name: 'Navigation link text: About', exact: true })).toHaveCount(1);
  await expect(editor.getByRole('textbox', { name: 'Navigation link text: Guides', exact: true })).toHaveCount(1);
});

test('Navigation Search toggles, positions, returns eligible results and excludes protected or unavailable documents', async ({ page }) => {
  await page.goto('/studio/ui/blocks/navigation');
  await expect(page.locator('.ui-block-specimen')).toHaveAttribute('data-ready', 'true');
  const editor = page.locator('.ui-library-canvas');
  await editor.getByRole('button', { name: 'Add Search', exact: true }).click();
  await expect(editor.getByRole('button', { name: 'Remove Search', exact: true })).toHaveAttribute('aria-pressed', 'true');
  const searchPreview = editor.locator('.navigation-search-preview');
  await expect(searchPreview).toBeVisible();
  await searchPreview.focus();
  await expect(searchPreview).toHaveClass(/is-selected/);
  await expect(searchPreview.getByRole('group', { name: 'Search block tools' })).toBeVisible();
  await expect(searchPreview.getByRole('button', { name: 'Select parent block: Navigation' })).toBeVisible();
  await searchPreview.getByRole('button', { name: 'Select parent block: Navigation' }).click();
  await searchPreview.click();
  const inspector = editor.locator('.navigation-search-inspector');
  await expect(inspector.getByRole('heading', { name: 'Search', exact: true })).toBeVisible();
  await inspector.getByRole('checkbox', { name: 'Show label', exact: true }).uncheck();
  await inspector.getByRole('textbox', { name: 'Placeholder text', exact: true }).fill('Find a page');
  await inspector.getByRole('textbox', { name: 'Placeholder text', exact: true }).press('Tab');
  await inspector.getByRole('combobox', { name: 'Button position', exact: true }).selectOption('button-only');
  await inspector.getByRole('spinbutton', { name: 'Input width (%)', exact: true }).fill('75');
  await inspector.getByRole('spinbutton', { name: 'Input width (%)', exact: true }).press('Tab');
  await expect(searchPreview).toHaveAttribute('data-button-position', 'button-only');
  await expect(searchPreview.locator('input[type="search"]')).toBeHidden();
  const iconToggle = inspector.getByRole('checkbox', { name: 'Use icon for button', exact: true });
  await expect(iconToggle).not.toBeChecked();
  await iconToggle.check();
  await expect(iconToggle).toBeChecked();
  await inspector.getByRole('tab', { name: 'Styles', exact: true }).click();
  await inspector.getByRole('button', { name: 'Advanced', exact: true }).click();
  await inspector.getByRole('textbox', { name: 'HTML anchor', exact: true }).fill('search-target');
  await inspector.getByRole('textbox', { name: 'Additional CSS class(es)', exact: true }).fill('custom-search');
  await inspector.getByRole('textbox', { name: 'Additional CSS', exact: true }).fill('color: #123456;');
  await expect(searchPreview).toHaveAttribute('id', 'search-target');
  await expect(searchPreview).toHaveClass(/custom-search/);
  await expect(searchPreview).toHaveCSS('color', 'rgb(18, 52, 86)');
  const rootItems = editor.locator('ul.template-navigation-items').first().locator(':scope > li');
  await expect(rootItems.nth(3)).toHaveClass(/navigation-search-preview/);
  await searchPreview.getByRole('button', { name: 'Move Search left', exact: true }).click();
  await expect(rootItems.nth(2)).toHaveClass(/navigation-search-preview/);

  await page.evaluate(() => {
    const fixtures = document.createElement('div');
    fixtures.id = 'navigation-search-fixtures';
    fixtures.innerHTML = '<section data-test-document="guide" data-test-searchable="true" data-test-title="Gutenberg guide"><div class="template-content-layout"><p>Navigation menus and Search</p></div></section><section data-test-document="protected" data-test-searchable="false" data-test-title="Protected page"><div class="template-content-layout"><p>cross-surface-secret</p></div></section><section data-test-document="scheduled" data-test-searchable="false" data-test-title="Scheduled page"><div class="template-content-layout"><p>Navigation future</p></div></section>';
    document.body.append(fixtures);
  });
  await page.getByRole('group', { name: 'Specimen view' }).getByRole('button', { name: 'Preview', exact: true }).click();
  const form = page.locator('.ui-block-canvas form[data-navigation-search]');
  await expect(form).toBeVisible();
  await expect(form).toHaveAttribute('data-button-position', 'button-only');
  await expect(form.locator('input[type="search"]')).toBeHidden();
  await expect(form.locator('input[type="search"]')).toHaveAttribute('placeholder', 'Find a page');
  await expect(page.locator('.ui-block-canvas #search-target')).toHaveClass(/custom-search/);
  await expect(page.locator('.ui-block-canvas #search-target')).toHaveCSS('color', 'rgb(18, 52, 86)');
  const openSearch = form.getByRole('button', { name: 'Open search' });
  await expect(openSearch).toHaveAttribute('data-icon', 'true');
  await openSearch.click();
  await expect(form.getByRole('searchbox')).toBeVisible();
  await form.getByRole('searchbox').fill('example');
  await form.getByRole('button', { name: 'Search' }).click();
  await expect(form.locator('[role="status"]')).toHaveText('3 results found.');
  await expect(form.locator('a[href="#home"]')).toHaveText('Home');
  await expect(form.locator('a[href="#about"]')).toHaveText('About');
  await expect(form.locator('a[href="#guides"]')).toHaveText('Guides');
  await form.getByRole('searchbox').fill('cross-surface-secret');
  await form.getByRole('button', { name: 'Search' }).click();
  await expect(form.locator('[role="status"]')).toHaveText('No results found.');
  await page.getByRole('group', { name: 'Specimen view' }).getByRole('button', { name: 'Edit', exact: true }).click();
  await page.getByRole('button', { name: 'Undo specimen change' }).click();
  await expect(editor.getByRole('button', { name: 'Add Search', exact: true })).toHaveAttribute('aria-pressed', 'false');
});
