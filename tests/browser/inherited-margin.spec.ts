  await page.keyboard.press('Escape');
  await expect(colour.locator('.studio-inherited-indicator')).toHaveCount(0);
  await block.getByRole('button', { name: 'Undo specimen change', exact: true }).click();
  await expect(colour.locator('.studio-inherited-indicator')).toBeVisible();
  await expect(widthIndicator).toHaveCount(0);
  await block.getByRole('button', { name: 'Undo specimen change', exact: true }).click();
  await expect(widthIndicator).toBeVisible();
  await block.getByRole('button', { name: 'Redo specimen change', exact: true }).click();
  await expect(widthIndicator).toHaveCount(0);
  await block.getByRole('button', { name: 'Reset Example', exact: true }).click();
  await block.getByRole('button', { name: 'Border options' }).click();
  await page.getByRole('group', { name: 'Border controls' }).getByRole('button', { name: 'Border', exact: true }).click();
  await page.keyboard.press('Escape');
  await expect(widthIndicator).toBeVisible();
  await expect(colour.locator('.studio-inherited-indicator')).toBeVisible();
  await block.getByRole('button', { name: 'Unlink border sides' }).click();
  const top = block.getByRole('spinbutton', { name: 'Border Top width' });
  await top.fill('3'); await top.blur();
  await expect(widthIndicator).toBeVisible();
