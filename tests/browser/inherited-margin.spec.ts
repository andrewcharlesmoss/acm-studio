test('website role hover is painted without the fallback darkening filter', async ({ page }) => {
  const { loadProductionModule } = await import('../production-module.mjs');
  const { websiteDesignRules } = await loadProductionModule(new URL('../../app/studio/site-editor/website-design-surface.tsx', import.meta.url));
  const css = websiteDesignRules({ paletteId: 'default', typographyId: 'default', colours: { elements: { links: { hover: '#3858e9' } } } }, 'role-hover');
  await page.setContent(`<style>.rich-text-editor a:hover { color: var(--studio-paragraph-link-hover-color, #1f4f88); filter: var(--studio-paragraph-link-hover-filter, brightness(.8)); } ${css}</style><div data-website-design="role-hover"><p class="paragraph-field rich-text-editor"><a href="#">Example</a></p></div>`);
  const anchor = page.locator('a');
  await anchor.hover();
  await expect(anchor).toHaveCSS('color', 'rgb(56, 88, 233)');
  await expect(anchor).toHaveCSS('filter', 'none');
  await anchor.evaluate(el => (el.parentElement as HTMLElement).style.setProperty('--studio-paragraph-link-hover-color', '#f6cff4'));
  await expect(anchor).toHaveCSS('color', 'rgb(246, 207, 244)');
  await expect(anchor).toHaveCSS('filter', 'none');
});


