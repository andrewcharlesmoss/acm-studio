  const picker = page.getByRole('dialog', { name: 'Border colour palette' });
  await expect(picker.locator('.studio-border-style .studio-inherited-indicator')).toBeVisible();
  await expect(picker.getByRole('combobox', { name: 'Border style' })).toHaveAccessibleDescription('Inherited border style');
