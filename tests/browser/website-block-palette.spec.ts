import { test, expect } from '@playwright/test';

test('Block inspector colour pickers use the current website palette', async ({ page }) => {
  await page.setViewportSize({ width: 1900, height: 1100 });
  await page.goto('/studio/ui/blocks/paragraph');
  await expect(page.locator('.ui-block-specimen')).toHaveAttribute('data-ready', 'true');
  const block = page.getByRole('complementary', { name: 'Paragraph Local Styles', exact: true });
  const site = page.getByRole('complementary', { name: 'Paragraph Global Styles', exact: true });
  const siteLink = site.getByRole('button', { name: 'Choose Link', exact: true });
  if (!(await siteLink.isVisible())) await site.getByText('Elements', { exact: true }).first().click();
  await siteLink.click();
  let picker = page.getByRole('dialog', { name: 'Link colour palette' });
  const labels = await picker.locator('.paragraph-colour-swatch').evaluateAll(els => els.map(el => el.getAttribute('aria-label')));
  await picker.locator('.paragraph-colour-swatch').nth(4).click(); await page.keyboard.press('Escape');
  await block.getByRole('button', { name: 'Elements options' }).click();
  await page.getByRole('group', { name: 'Elements controls' }).getByRole('button', { name: 'Link', exact: true }).click(); await page.keyboard.press('Escape');
  const link = block.getByRole('button', { name: /^Choose Link/ });
  await link.click(); picker = page.getByRole('dialog', { name: 'Link colour palette' });
  expect(await picker.locator('.paragraph-colour-swatch').evaluateAll(els => els.map(el => el.getAttribute('aria-label')))).toEqual(labels);
  await expect(picker.locator('.paragraph-colour-swatch').nth(4)).toHaveAttribute('aria-pressed', 'true');
  await expect(picker.getByRole('button', { name: 'Clear', exact: true })).toHaveCount(0);
  await picker.getByRole('button', { name: 'Custom link colour picker' }).click();
  await expect(page.getByRole('dialog', { name: 'Custom link colour' }).getByRole('slider', { name: 'Alpha' })).toBeVisible();
  await page.keyboard.press('Escape');
  await picker.locator('.paragraph-colour-swatch').nth(2).click(); await page.keyboard.press('Escape');
  await expect(page.locator('.ui-block-canvas .rich-text-editor a').first()).toHaveCSS('color', 'rgb(255, 238, 88)');
  await link.click(); picker = page.getByRole('dialog', { name: 'Link colour palette' });
  await picker.getByRole('button', { name: 'Clear', exact: true }).click(); await page.keyboard.press('Escape');
  await expect(page.locator('.ui-block-canvas .rich-text-editor a').first()).toHaveCSS('color', 'rgb(80, 58, 168)');
  await block.getByRole('button', { name: /^Choose Colour/ }).click();
  picker = page.getByRole('dialog', { name: 'Colour palette', exact: true });
  expect(await picker.locator('.paragraph-colour-swatch').evaluateAll(els => els.map(el => el.getAttribute('aria-label')))).toEqual(labels);
  await page.keyboard.press('Escape');
  await block.getByRole('button', { name: 'Colour', exact: true }).click();
  picker = page.getByRole('dialog', { name: 'Background colour palette' });
  expect(await picker.locator('.paragraph-colour-swatch').evaluateAll(els => els.map(el => el.getAttribute('aria-label')))).toEqual(labels);
  await page.keyboard.press('Escape');
  await block.getByRole('button', { name: 'Border options' }).click();
  await page.getByRole('group', { name: 'Border controls' }).getByRole('button', { name: 'Border', exact: true }).click();
  await page.keyboard.press('Escape');
  await block.getByRole('button', { name: 'Choose border colour for all sides (All control)' }).click();
  picker = page.getByRole('dialog', { name: 'Border colour palette' });
  expect(await picker.locator('.paragraph-colour-swatch').evaluateAll(els => els.map(el => el.getAttribute('aria-label')))).toEqual(labels);
});
